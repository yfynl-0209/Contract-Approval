#: A4 纵向，PDF 点（1 pt = 1/72 inch）。与 M4 标准文档的 `pdf-point-top-left` 一致。
PAGE_WIDTH_PT = 595.0
PAGE_HEIGHT_PT = 842.0
MARGIN_LEFT_PT = 72.0
#: 首行基线 y。⚠️ **左上原点，数值增大表示向下。**
#:
#: 实测依据：`insert_text(Point(72, 770), ...)` 在 842 高的页面上得到的文本 bbox 是
#: `y0=758.0 y1=772.4` —— 也就是落在页面**底部**。PyMuPDF 的页面坐标不是 PDF 规范里
#: 那个"左下原点的用户空间"，两者相差一次上下翻转。
#: 沿用"数值大表示靠上"的直觉写出来的文档是**上下颠倒**的（标题在底部）。
FIRST_BASELINE_PT = 72.0
LINE_HEIGHT_PT = 16.0
FONT_SIZE_PT = 12.0
#: 扫描件渲染 DPI：200 是中文 OCR 的常用下限，再低小字会糊
SCAN_DPI = 200


def line_baseline(index: int) -> float:
    """第 `index` 行（0 起）的 PDF 基线 y 坐标（**左上原点，逐行向下递增**）。

    验收 5 要"用**已知**坐标写入文本，再反查 OCR 结果落在容差内" ——
    已知就来自这里。生成与断言共用同一个函数，坐标不可能各算一份。

    ⚠️ 必须**递增**。递减会让页面上下颠倒（标题跑到底部、末条跑到上方），
    而各种症状里最隐蔽的一种是：文本件的抽取顺序仍按**内容流**（看起来正常），
    但 OCR 读的是**图像**、按 y 从小到大读 —— 同一份内容的文本件与扫描件
    会给出**相反**的正文顺序，而验收 3 要的恰恰是两者一致。
    """
    return FIRST_BASELINE_PT + index * LINE_HEIGHT_PT


